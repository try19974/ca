import cv2

# เปิดกล้อง (เลข 0 คือกล้องตัวแรกของเครื่อง ถ้าไม่ติดลองเปลี่ยนเป็น 1 หรือ 2)
cap = cv2.VideoCapture(0)

# เช็คว่ากล้องเปิดสำเร็จไหม
if not cap.isOpened():
    print("❌ ไม่สามารถเปิดกล้องได้ เช็คสาย USB หรือสิทธิ์การเข้าถึงกล้อง")
    exit()

print("✅ เปิดกล้องสำเร็จ! (คลิกที่หน้าต่างกล้องแล้วกดปุ่ม 'q' เพื่อปิด)")

while True:
    # อ่านภาพจากกล้องทีละเฟรม
    ret, frame = cap.read()

    # ถ้าอ่านภาพไม่ได้ให้หยุดการทำงาน
    if not ret:
        print("❌ ไม่สามารถรับภาพจากกล้องได้")
        break

    # แสดงภาพในหน้าต่างชื่อ 'My Camera'
    cv2.imshow('My Camera', frame)

    # รอรับคำสั่งจากคีย์บอร์ด 1 มิลลิวินาที 
    # ถ้ากดปุ่ม 'q' (ภาษาอังกฤษ) ให้หยุดการทำงาน (ออกจากลูป)
    if cv2.waitKey(1) & 0xFF == ord('q'):
        break

# คืนการเข้าถึงกล้องให้ระบบ และปิดหน้าต่างทั้งหมด
cap.release()
cv2.destroyAllWindows()